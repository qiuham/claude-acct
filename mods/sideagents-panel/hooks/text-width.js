function isWide(code) {
  let low = 0
  let high = WIDE_RANGES.length - 1
  while (low <= high) {
    const mid = (low + high) >> 1
    const [start, stop] = WIDE_RANGES[mid]
    if (code < start) high = mid - 1
    else if (code > stop) low = mid + 1
    else return true
  }
  return false
}
