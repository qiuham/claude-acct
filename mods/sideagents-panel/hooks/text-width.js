// 显示宽度（终端里占几格），横条、详情页、接管挑选框共用。

// 显示宽度：照 Claude Code 的 ie() = Bun.stringWidth(text, { ambiguousIsNarrow: true })。
// 东亚宽字符、全角、表情算 2 格；宽度不定的（↓ ↑ · … ◯ ❯ 这些）算 1 格；
// 控制字符、组合附加符号、零宽字符、变体选择符算 0 格；零宽连接（ZWJ）后面那个字并进前一个，不另算。
export function displayWidth(text) {
  let width = 0
  let joined = false
  let last = 0
  for (const ch of String(text || '')) {
    const code = ch.codePointAt(0)
    if (joined) {
      joined = false
      continue
    }
    if (code === 0x200d) {
      joined = true
      continue
    }
    if (code === 0xfe0f) {
      // 表情显示形式：前一个字原本算 1 格的，按 2 格算
      if (last === 1) width += 1
      last = 0
      continue
    }
    last = charWidthOf(code)
    width += last
  }
  return width
}

export function charWidthOf(code) {
  if (code < 0x20 || (code >= 0x7f && code < 0xa0)) return 0
  if (isZeroWidth(code)) return 0
  return isWide(code) ? 2 : 1
}

function isZeroWidth(code) {
  return (code >= 0x300 && code <= 0x36f) || (code >= 0x483 && code <= 0x489)
    || (code >= 0x591 && code <= 0x5bd) || (code >= 0x610 && code <= 0x61a)
    || (code >= 0x64b && code <= 0x65f) || (code >= 0x1ab0 && code <= 0x1aff)
    || (code >= 0x1dc0 && code <= 0x1dff) || (code >= 0x200b && code <= 0x200f)
    || (code >= 0x2028 && code <= 0x202e) || (code >= 0x2060 && code <= 0x2064)
    || (code >= 0x20d0 && code <= 0x20ff) || (code >= 0xfe00 && code <= 0xfe0f)
    || (code >= 0xfe20 && code <= 0xfe2f) || code === 0xfeff
    || (code >= 0xe0000 && code <= 0xe0fff) || (code >= 0x1f3fb && code <= 0x1f3ff)
}

